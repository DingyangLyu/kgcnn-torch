"""Generic dataset wrapper for an existing ``*.kgcnn.pickle`` cache.

This is mainly intended for strict Keras↔Torch alignment: if you already have a
KGCNN pickle generated by the Keras pipeline, you can load it byte-identically
and convert to PyG ``Data`` objects via ``to_pyg_list()``.
"""

from typing import Optional

from kgcnn_torch.data.datasets._base import KgcnnGraphDataset


class PickleGraphDataset(KgcnnGraphDataset):
    """Load a pre-built ``*.kgcnn.pickle`` and expose it as a PyG dataset."""

    dataset_name = "PickleGraphDataset"
    download_info = {}

    def __init__(self, pickle_path: str,
                 dataset_name: str = "PickleGraphDataset",
                 root: Optional[str] = None,
                 transform=None, pre_transform=None, pre_filter=None,
                 reload: bool = False,
                 **kwargs):
        self.dataset_name = str(dataset_name)
        super().__init__(
            root=root,
            transform=transform,
            pre_transform=pre_transform,
            pre_filter=pre_filter,
            reload=reload,
            kgcnn_pickle_path=pickle_path,
            **kwargs,
        )

